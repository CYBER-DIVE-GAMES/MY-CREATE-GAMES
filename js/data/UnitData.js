// アップグレード後のステータスを計算する関数
function getUpgradedStats(unitKey, upgrades) {
    const base = { ...UNIT_DATA[unitKey] };
    const upg = upgrades[unitKey] || { hp: 0, attack: 0, speed: 0 };

    base.hp = Math.floor(base.hp * (1 + upg.hp * 0.15));
    base.attack = Math.floor(base.attack * (1 + upg.attack * 0.15));
    base.speed = Math.floor(base.speed * (1 + upg.speed * 0.1));

    return base;
}
